// Builds mock/bank.js (Exam 2 + Classification) and review/bank.js (all drills) from the question banks.
// Run after changing any question bank:  node tools/build-mock.js
const fs = require("fs"), vm = require("vm"), path = require("path");
const root = path.join(__dirname, "..");
function load(dir) {
  const ctx = { window: {} }; vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(root, dir, "questions.js"), "utf8"), ctx);
  return ctx.window.BANK;
}
const out = [], seen = new Set();
function add(dir, B, subjectOf) {
  for (const d in B.ids) for (const id of B.ids[d]) {
    const q = B.q[id]; if (q.dup) continue;
    const key = q.q + "|" + q.ok; if (seen.has(key)) continue; seen.add(key);   // the 36 shared worksheet questions appear once
    const img = q.img || (B.img && B.img[id]);
    out.push({ id: dir + ":" + id, subject: subjectOf(q), src: q.src || B.decks[q.d].src || B.decks[q.d].name,
      tag: q.tag, q: q.q, ok: q.ok, wrong: q.wrong, ex: q.ex || "", img: img ? ["../" + dir + "/" + img[0], img[1]] : null });
  }
}
const e2 = load("exam2"), cl = load("classification");
const short = {}; (e2.topics || []).forEach(t => short[t.name] = t.short || t.name);
add("exam2", e2, q => short[q.topic] || q.topic);
add("classification", cl, () => "Classification chart");
fs.writeFileSync(path.join(root, "mock", "bank.js"),
  "// Generated by tools/build-mock.js. Do not edit by hand.\nwindow.MOCK_BANK = " + JSON.stringify(out) + ";\n");
const by = {}; out.forEach(x => by[x.subject] = (by[x.subject] || 0) + 1);
console.log(out.length + " questions", by);

// ----- review/bank.js: every question from every drill, keyed by drill + question id,
// so the Review page can show the questions a student has marked for review.
const DRILLS = [
  { dir: "exam2", name: "Exam 2", B: e2 },
  { dir: "classification", name: "Classification", B: cl },
  { dir: "exam1", name: "Exam 1", B: load("exam1") }
];
const review = {};
for (const { dir, name, B } of DRILLS) {
  const sh = {}; (B.topics || []).forEach(t => sh[t.name] = t.short || t.name);
  const items = {};
  for (const d in B.ids) for (const id of B.ids[d]) {
    const q = B.q[id]; if (q.dup) continue;
    const img = q.img || (B.img && B.img[id]);
    items[id] = { subject: sh[q.topic] || q.topic || name, src: q.src || B.decks[q.d].src || B.decks[q.d].name, tag: q.tag,
      q: q.q, ok: q.ok, wrong: q.wrong, ex: q.ex || "", img: img ? ["../" + dir + "/" + img[0], img[1]] : null };
  }
  review[dir] = { name, key: B.storageKey, html: !B.textOnly, href: "../" + dir + "/index.html", items };
}
fs.mkdirSync(path.join(root, "review"), { recursive: true });
fs.writeFileSync(path.join(root, "review", "bank.js"),
  "// Generated by tools/build-mock.js. Do not edit by hand.\nwindow.REVIEW_BANK = " + JSON.stringify(review) + ";\n");
console.log("review bank:", Object.entries(review).map(([k, v]) => k + " " + Object.keys(v.items).length).join(", "));
