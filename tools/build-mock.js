// Builds mock/bank.js: every question from the Exam 2 and Classification drills, as one list.
// Run after changing either question bank:  node tools/build-mock.js
const fs = require("fs"), vm = require("vm"), path = require("path");
const root = path.join(__dirname, "..");
function load(dir) {
  const ctx = { window: {} }; vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(root, dir, "questions.js"), "utf8"), ctx);
  return ctx.window.BANK;
}
const out = [], seen = new Set();
function add(dir, B, subjectOf) {
  for (const d in B.ids) for (const id of B.ids[d]) {
    const q = B.q[id]; if (q.dup) continue;
    const key = q.q + "|" + q.ok; if (seen.has(key)) continue; seen.add(key);   // the 36 shared worksheet questions appear once
    const img = q.img || (B.img && B.img[id]);
    out.push({ id: dir + ":" + id, subject: subjectOf(q), src: q.src || B.decks[q.d].src || B.decks[q.d].name,
      tag: q.tag, q: q.q, ok: q.ok, wrong: q.wrong, ex: q.ex || "", img: img ? ["../" + dir + "/" + img[0], img[1]] : null });
  }
}
const e2 = load("exam2"), cl = load("classification");
const short = {}; (e2.topics || []).forEach(t => short[t.name] = t.short || t.name);
add("exam2", e2, q => short[q.topic] || q.topic);
add("classification", cl, () => "Classification chart");
fs.writeFileSync(path.join(root, "mock", "bank.js"),
  "// Generated by tools/build-mock.js. Do not edit by hand.\nwindow.MOCK_BANK = " + JSON.stringify(out) + ";\n");
const by = {}; out.forEach(x => by[x.subject] = (by[x.subject] || 0) + 1);
console.log(out.length + " questions", by);
